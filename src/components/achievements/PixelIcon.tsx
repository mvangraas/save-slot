export function PixelIcon({ icon, className }: { icon: IconKey; className?: string }) {
  const rows = GLYPHS[icon]
  return (
    <svg
      viewBox="0 0 8 8"
      aria-hidden
      focusable="false"
      shapeRendering="crispEdges"
      className={className}
    >
      {rows.flatMap((row, y) =>
        [...row].map((px, x) =>
          px === '#' ? (
            <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" />
          ) : null,
        ),
      )}
    </svg>
  )
}

export const iconKeys = Object.keys(GLYPHS) as IconKey[]
